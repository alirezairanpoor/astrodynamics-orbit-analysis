def load_jgm3_gravity_model() -> tuple[np.ndarray, np.ndarray]:
    """
    Return unnormalized JGM-3 coefficients through degree/order 20.

    Source:
        Montenbruck & Gill, Table 3.3.

    Uses the rounded coefficients printed in the book,
    not the full-precision original JGM-3 dataset.

    Use together with JGM3_MU and JGM3_RADIUS.
    """

    rows = np.fromstring(_TABLE, sep=" ").reshape(-1, 4)

    expected_pairs = {
        (n, m)
        for n in range(2, 21)
        for m in range(n + 1)
    }

    actual_pairs = {
        (int(n), int(m))
        for n, m, _, _ in rows
    }

    if len(rows) != 228 or actual_pairs != expected_pairs:
        raise ValueError("Incomplete or duplicated JGM-3 table.")

    C_normalized = np.zeros((21, 21))
    S_normalized = np.zeros((21, 21))

    # Central gravity; degree-one terms remain zero.
    C_normalized[0, 0] = 1.0

    for n, m, c, s in rows:
        n = int(n)
        m = int(m)

        C_normalized[n, m] = c * 1e-6
        S_normalized[n, m] = s * 1e-6

    C, S = unnormalize_gravity_coefficients(
        C_normalized,
        S_normalized,
    )

    return C, S
